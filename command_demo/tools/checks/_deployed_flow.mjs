import puppeteer from "puppeteer-core";
import fs from "node:fs";
const EDGE = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"].find((p)=>fs.existsSync(p));
const b = await puppeteer.launch({executablePath:EDGE,headless:"new",args:["--enable-unsafe-swiftshader","--use-angle=swiftshader","--hide-scrollbars","--window-size=1600,900"]});
const st = await b.newPage(); const errs=[]; st.on("pageerror",e=>errs.push(e.message));
await st.setViewport({width:1600,height:900});
await st.goto("https://blog.srlove.top/aegis/",{waitUntil:"domcontentloaded",timeout:60000});
await new Promise(r=>setTimeout(r,22000));
const tb = await b.newPage();
await tb.setViewport({width:1180,height:820});
await tb.goto("https://blog.srlove.top/aegis/tablet",{waitUntil:"networkidle2",timeout:60000});
await new Promise(r=>setTimeout(r,1200));
console.log("health", await tb.evaluate(()=>document.querySelector(".health")?.textContent?.trim()));
await tb.click(".model:nth-child(4) .fire-btn:nth-child(1)");
await new Promise(r=>setTimeout(r,3400));
await st.screenshot({path:"shots/deployed_flow.png"});
console.log("state", await st.evaluate(()=>({scene:document.querySelector(".tab.on")?.textContent, title:document.querySelector("#visitorTitle")?.textContent, cards:document.querySelectorAll(".dk-card").length})));
console.log("errors", errs.slice(0,4));
await b.close();
