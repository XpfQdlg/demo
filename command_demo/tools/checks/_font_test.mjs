import puppeteer from "puppeteer-core";
import fs from "node:fs";
const EDGE = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"].find((p)=>fs.existsSync(p));
const b = await puppeteer.launch({executablePath:EDGE,headless:"new",args:["--enable-unsafe-swiftshader","--use-angle=swiftshader","--hide-scrollbars","--window-size=1600,900"]});
const p = await b.newPage();
await p.setViewport({width:1600,height:900});
await p.goto("http://localhost:5179/",{waitUntil:"domcontentloaded",timeout:60000});
await new Promise(r=>setTimeout(r,24000));
await p.evaluate(()=>{ document.documentElement.style.setProperty("--font", '"DengXian","Microsoft YaHei UI",sans-serif'); document.documentElement.style.setProperty("--num", '"Bahnschrift","DIN Alternate",sans-serif'); });
await new Promise(r=>setTimeout(r,800));
await p.screenshot({path:"shots/font_dengxian.png"});
await p.evaluate(()=>{ document.documentElement.style.setProperty("--font", '"Microsoft YaHei UI","Microsoft YaHei",sans-serif'); });
await new Promise(r=>setTimeout(r,800));
await p.screenshot({path:"shots/font_yaheiui.png"});
await b.close();
